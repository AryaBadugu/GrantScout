"""
Draft export: DOCX and PDF with DRAFT watermark and verify-on-portal footer.
Requires python-docx and reportlab.
"""
from __future__ import annotations

import io
import logging
from datetime import datetime
from pathlib import Path

logger = logging.getLogger(__name__)


def export_draft_docx(
    draft_text: str,
    grant_name: str,
    startup_name: str,
    checklist: list[str],
) -> bytes:
    """
    Export an approved draft as a DOCX file.
    Returns bytes of the .docx file.
    """
    from docx import Document
    from docx.shared import Pt, RGBColor, Inches
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    doc = Document()

    # Title
    title = doc.add_heading("DRAFT – REVIEW BEFORE SUBMISSION", 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in title.runs:
        run.font.color.rgb = RGBColor(0xB7, 0x1C, 0x1C)

    doc.add_heading(f"Grant Application: {grant_name}", 1)
    doc.add_paragraph(f"Startup: {startup_name}")
    doc.add_paragraph(f"Generated: {datetime.now().strftime('%d %b %Y %H:%M')} (AI-generated, verify before submission)")
    doc.add_paragraph("")

    # Body
    for line in draft_text.split("\n"):
        if line.startswith("⚠️") or line.startswith("#"):
            continue
        if line.strip().startswith(("1.", "2.", "3.", "4.", "5.", "6.", "7.")):
            doc.add_heading(line.strip(), 2)
        elif line.strip():
            doc.add_paragraph(line.strip())

    # Checklist
    doc.add_page_break()
    doc.add_heading("Required Documents Checklist", 1)
    for item in checklist:
        p = doc.add_paragraph(style="List Bullet")
        p.add_run(f"☐  {item}")

    # Footer notice
    doc.add_paragraph("")
    footer_para = doc.add_paragraph()
    footer_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = footer_para.add_run(
        "⚠️ DRAFT – All deadlines, funding amounts and eligibility criteria "
        "MUST be independently verified on the official grant portal before submission. "
        "This document was AI-generated by GrantScout (IBM Granite on watsonx.ai)."
    )
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0x6B, 0x78, 0x90)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def export_draft_pdf(
    draft_text: str,
    grant_name: str,
    startup_name: str,
    checklist: list[str],
) -> bytes:
    """
    Export an approved draft as a PDF file.
    Returns bytes of the .pdf file.
    """
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import cm
    from reportlab.lib import colors
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
    from reportlab.lib.enums import TA_CENTER, TA_LEFT

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=2*cm, rightMargin=2*cm,
        topMargin=2*cm, bottomMargin=2*cm,
    )

    styles = getSampleStyleSheet()
    story = []

    # Watermark title
    draft_style = ParagraphStyle(
        "DraftTitle", parent=styles["Title"],
        textColor=colors.HexColor("#B71C1C"),
        fontSize=16, spaceAfter=8,
    )
    story.append(Paragraph("⚠ DRAFT – REVIEW BEFORE SUBMISSION", draft_style))
    story.append(Spacer(1, 6))

    heading2 = ParagraphStyle("H2", parent=styles["Heading2"], textColor=colors.HexColor("#0F3460"))
    story.append(Paragraph(f"Grant Application: {grant_name}", heading2))
    story.append(Paragraph(f"Startup: {startup_name}", styles["Normal"]))
    story.append(Paragraph(
        f"Generated: {datetime.now().strftime('%d %b %Y %H:%M')}",
        ParagraphStyle("meta", parent=styles["Normal"], textColor=colors.gray, fontSize=9),
    ))
    story.append(Spacer(1, 12))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#DDE3EE")))
    story.append(Spacer(1, 10))

    # Body paragraphs
    body_style = ParagraphStyle("Body", parent=styles["Normal"], fontSize=10, leading=15)
    section_style = ParagraphStyle("Section", parent=styles["Heading3"], textColor=colors.HexColor("#1565C0"))
    for line in draft_text.split("\n"):
        stripped = line.strip()
        if not stripped or stripped.startswith("⚠️"):
            continue
        if stripped[:2] in ("1.", "2.", "3.", "4.", "5.", "6.", "7."):
            story.append(Spacer(1, 8))
            story.append(Paragraph(stripped, section_style))
        else:
            story.append(Paragraph(stripped.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"), body_style))
            story.append(Spacer(1, 4))

    # Checklist
    story.append(Spacer(1, 12))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#DDE3EE")))
    story.append(Spacer(1, 8))
    story.append(Paragraph("Required Documents Checklist", heading2))
    for item in checklist:
        story.append(Paragraph(f"☐  {item}", body_style))

    # Footer
    story.append(Spacer(1, 20))
    footer_style = ParagraphStyle(
        "Footer", parent=styles["Normal"], fontSize=8,
        textColor=colors.gray, alignment=TA_CENTER,
    )
    story.append(Paragraph(
        "⚠ DRAFT – Verify all details on the official portal before submission. "
        "Generated by GrantScout (IBM Granite · watsonx.ai Lite).",
        footer_style,
    ))

    doc.build(story)
    return buf.getvalue()
